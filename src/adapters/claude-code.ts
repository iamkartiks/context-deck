/**
 * Claude Code
 *
 * Layout:  <CLAUDE_CONFIG_DIR or ~/.claude>/projects/<encoded-cwd>/<session-id>.jsonl
 * Subagents: …/<encoded-cwd>/<session-id>/subagents/<agent>.jsonl
 *            (older versions: …/<encoded-cwd>/agent-<id>.jsonl with isSidechain lines)
 *
 * Each line is one event: { type: "user" | "assistant" | "summary" | "system" | …,
 *   sessionId, uuid, parentUuid, timestamp, cwd, gitBranch, version, message: {…} }
 *
 * The format is not officially documented and changes between versions, so
 * every field is read defensively and unknown line types are ignored.
 */

const EDIT_TOOLS = new Set(['Edit', 'MultiEdit', 'Write', 'NotebookEdit']);

/** Wrapper messages Claude Code inserts that are not real user prompts. */
const NOISE_PREFIXES = [
  '<local-command-stdout>',
  '<local-command-stderr>',
  '<system-reminder>',
  'Caveat: The messages below were generated by the user while running local commands',
  '[Request interrupted by user',
];

function commandFromWrapper(text: string): string | null {
  const name = /<command-name>([^<]*)<\/command-name>/.exec(text)?.[1]?.trim();
  if (!name) return null;
  const args = /<command-args>([\s\S]*?)<\/command-args>/.exec(text)?.[1]?.trim();
  return args ? `${name} ${args}` : name;
}

/** Best-effort reverse of Claude Code's folder naming (/ and . become -). Lossy. */
export function decodeProjectDir(dirName: string): string {
  return dirName.replace(/-/g, '/');
}

function summariseToolInput(name: string, input: unknown): string {
  if (!input || typeof input !== 'object') return name;
  const i = input as Record<string, unknown>;
  const target =
    asString(i.file_path) ??
    asString(i.notebook_path) ??
    asString(i.command) ??
    asString(i.pattern) ??
    asString(i.url) ??
    asString(i.query) ??
    asString(i.description) ??
    asString(i.prompt);
  if (target) return `${name}: ${target}`;
  try {
    return `${name}: ${JSON.stringify(input)}`;
  } catch {
    return name;
  }
}

async function parse(filePath: string): Promise<ParseResult> {
  const file = basename(filePath, '.jsonl');
  const segments = filePath.split(sep);
  const subIdx = segments.lastIndexOf('subagents');

  let parentNativeId: string | null = null;
  let isSubagent = false;
  let nativeIdFromPath = file;
  if (subIdx > 0) {
    // …/<parent-session-id>/subagents/<agent>.jsonl
    isSubagent = true;
    parentNativeId = segments[subIdx - 1] ?? null;
    nativeIdFromPath = `${parentNativeId}/${file}`;
  } else if (file.startsWith('agent-')) {
    // Older layout: agent-<id>.jsonl next to the parent, lines carry the parent's sessionId.
    isSubagent = true;
  }

  const s: NormalizedSession = emptySession('claude-code', nativeIdFromPath);
  s.isSubagent = isSubagent;
  s.parentNativeId = parentNativeId;

  let badLines = 0;
  const warnings: string[] = [];
  let summaryTitle: string | null = null;
  let customTitle: string | null = null;
  let firstPrompt: string | null = null;
  let firstCommand: string | null = null;
  let sessionIdField: string | null = null;
  const toolNames = new Map<string, string>(); // tool_use id → name
  const seenUsage = new Set<string>(); // message.id, so streamed chunks are counted once
  const files = new Set<string>();
  const editedAt = new Map<string, string>();
  let seq = 0;

  const push = (role: NormalizedSession['messages'][number]['role'], text: string, ts: unknown, toolName?: string) => {
    if (!text) return;
    s.messages.push({ seq: seq++, role, ts: asString(ts), text, ...(toolName ? { toolName } : {}) });
  };

  for await (const line of readJsonl(filePath)) {
    if (!line.ok) {
      badLines++;
      continue;
    }
    const o = line.value as Record<string, unknown>;
    if (!o || typeof o !== 'object') continue;
    const type = o.type;

    if (type === 'summary') {
      summaryTitle = asString(o.summary) ?? summaryTitle;
      continue;
    }
    if (type === 'custom-title') {
      customTitle = asString(o.customTitle) ?? asString(o.title) ?? customTitle;
      continue;
    }

    sessionIdField ??= asString(o.sessionId);
    s.cwd ??= asString(o.cwd);
    s.gitBranch = asString(o.gitBranch) ?? s.gitBranch;
    s.cliVersion = asString(o.version) ?? s.cliVersion;
    trackTime(s, o.timestamp);

    if (type === 'system') {
      if (o.subtype === 'compact_boundary') {
        s.compactions++;
        s.compactionPoints.push(s.contextSeries.length);
      }
      continue;
    }

    // In a main session file, sidechain lines belong to an inline subagent; skip their messages.
    if (o.isSidechain === true && !isSubagent) continue;

    const msg = o.message as Record<string, unknown> | undefined;
    if (!msg || typeof msg !== 'object') continue;

    if (type === 'user') {
      if (o.isMeta === true) continue;
      const content = msg.content;

      if (Array.isArray(content)) {
        let userText = '';
        for (const block of content as Record<string, unknown>[]) {
          if (block?.type === 'tool_result') {
            const name = toolNames.get(String(block.tool_use_id)) ?? 'tool';
            const out = textFromContent(block.content);
            push('tool', clean(`${name} result: ${out}`, MAX_TOOL_CHARS), o.timestamp, name);
          } else if (block?.type === 'text' && typeof block.text === 'string') {
            userText += (userText ? '\n' : '') + block.text;
          } else if (block?.type === 'image') {
            userText += (userText ? '\n' : '') + '[image]';
          }
        }
        if (userText && !NOISE_PREFIXES.some((p) => userText.startsWith(p))) {
          s.userTurns++;
          firstPrompt ??= userText;
          push('user', clean(userText), o.timestamp);
        }
      } else if (typeof content === 'string') {
        const command = commandFromWrapper(content);
        if (command) {
          firstCommand ??= command;
          push('user', clean(command), o.timestamp);
        } else if (!NOISE_PREFIXES.some((p) => content.startsWith(p))) {
          s.userTurns++;
          firstPrompt ??= content;
          push('user', clean(content), o.timestamp);
        }
      }
      continue;
    }

    if (type === 'assistant') {
      s.model = asString(msg.model) ?? s.model;
      const usage = msg.usage as Record<string, unknown> | undefined;
      const usageKey = asString(msg.id) ?? asString(o.uuid) ?? String(line.lineNo);
      if (usage && !seenUsage.has(usageKey)) {
        seenUsage.add(usageKey);
        const input =
          asNumber(usage.input_tokens) +
          asNumber(usage.cache_creation_input_tokens) +
          asNumber(usage.cache_read_input_tokens);
        s.tokensIn += input;
        s.tokensOut += asNumber(usage.output_tokens);
        s.contextTokens = input + asNumber(usage.output_tokens);
        s.contextSeries.push(s.contextTokens);
        s.assistantTurns++;
      }
      const content = msg.content;
      const blocks = Array.isArray(content) ? (content as Record<string, unknown>[]) : [];
      if (typeof content === 'string') push('assistant', clean(content), o.timestamp);
      for (const block of blocks) {
        if (block?.type === 'text' && typeof block.text === 'string') {
          push('assistant', clean(block.text), o.timestamp);
        } else if (block?.type === 'tool_use') {
          const name = asString(block.name) ?? 'tool';
          if (typeof block.id === 'string') toolNames.set(block.id, name);
          s.toolCalls++;
          const input = block.input as Record<string, unknown> | undefined;
          if (EDIT_TOOLS.has(name) && input) {
            const f = asString(input.file_path) ?? asString(input.notebook_path);
            if (f) {
              files.add(f);
              noteEdit(editedAt, f, o.timestamp);
            }
          }
          push('tool', clean(summariseToolInput(name, input), MAX_TOOL_CHARS), o.timestamp, name);
        }
        // thinking / redacted_thinking blocks are intentionally not indexed
      }
    }
  }

  if (sessionIdField && !s.isSubagent) s.nativeId = sessionIdField;
  if (file.startsWith('agent-') && subIdx < 0) {
    s.parentNativeId = sessionIdField;
    s.nativeId = file;
  }
  if (!s.cwd) {
    const projectDir = s.isSubagent && subIdx > 0 ? segments[subIdx - 2] : basename(dirname(filePath));
    if (projectDir) s.cwd = decodeProjectDir(projectDir);
  }

  s.filesTouched = [...files];
  s.fileEditedAt = Object.fromEntries(editedAt);
  s.title = titleFrom(customTitle ?? summaryTitle ?? firstPrompt ?? firstCommand ?? '') || '(untitled session)';

  if (s.messages.length === 0 && !summaryTitle) {
    // e.g. files that only hold file-history snapshots
    return { session: null, badLines, warnings: [...warnings, 'no conversation found'] };
  }
  return { session: s, badLines, warnings };
}

function shellQuote(s: string): string {
  return /^[A-Za-z0-9_./~:@%+=-]+$/.test(s) ? s : `'${s.replace(/'/g, `'\\''`)}'`;
}

export const claudeCodeAdapter: Adapter = {
  id: 'claude-code',
  label: 'Claude Code',
  shortPrefix: 'cc',
  envVar: 'CONTEXTDECK_CLAUDE_DIR',

  defaultRoot(env, home) {
    return env.CONTEXTDECK_CLAUDE_DIR ?? env.CLAUDE_CONFIG_DIR ?? join(home, '.claude');
  },

  async discover(root) {
    return listFiles(join(root, 'projects'), (rel) => rel.endsWith('.jsonl'));
  },

  parse,

  // `claude "prompt"` starts an interactive session with an initial prompt.
  startCommand: () => ({ command: 'claude', args: [] }),
  defaultContextWindow: 200_000,

  resumeCommand(session: SessionRow): ResumeCommand {
    // Subagents can't be resumed on their own; resume the parent conversation.
    const id = session.isSubagent && session.parentId ? session.parentId.split(':').slice(1).join(':') : session.nativeId;
    const args = ['--resume', id];
    const cwd = session.cwd;
    const display = `${cwd ? `cd ${shellQuote(cwd)} && ` : ''}claude ${args.map(shellQuote).join(' ')}`;
    return { command: 'claude', args, cwd, display: truncate(display, 400) };
  },
};
